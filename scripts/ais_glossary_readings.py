PSEUDONYM_READING_STEMS: dict[str, str] = {
    "顧客": "こきゃく",
    "担当者": "たんとうしゃ",
}


def pseudonym_reading(pseudonym: str) -> str:
    """Derive the reading of a de-identified label such as `顧客A`."""
    for stem, reading in PSEUDONYM_READING_STEMS.items():
        if pseudonym.startswith(stem):
            return f"{reading}{pseudonym[len(stem):].lower()}"
    raise ValueError(f"No reading stem for pseudonym: {pseudonym}")
